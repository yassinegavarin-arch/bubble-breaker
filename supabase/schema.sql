-- ---------------------------------------------------------------
-- Personnalités suivies
-- ---------------------------------------------------------------
create table if not exists personalities (
  id            bigint generated by default as identity primary key,
  slug          text not null unique,
  first_name    text,
  last_name     text not null,               -- affiché en MAJUSCULES
  country       text not null,               -- code ISO : FR, US, BR...
  role          text,                        -- fonction ou parti, une ligne
  search_terms  text[] not null,             -- termes détectés dans les titres
  news_editions text[] not null default '{fr}', -- éditions Google News : fr, en, pt, es, it, de
  active        boolean not null default true,
  created_at    timestamptz not null default now()
);

-- ---------------------------------------------------------------
-- Médias et leur sensibilité éditoriale (classement provisoire, public)
-- ---------------------------------------------------------------
create table if not exists sources (
  id          bigint generated by default as identity primary key,
  domain      text not null unique,          -- ex : lefigaro.fr
  name        text not null,
  country     text not null,
  leaning     text not null check (leaning in ('gauche','centre-gauche','centre','centre-droit','droite')),
  feed_url    text,                          -- flux RSS direct, facultatif
  active      boolean not null default true,
  last_ok_at  timestamptz,
  last_error  text
);

-- ---------------------------------------------------------------
-- Articles collectés (titre, extrait court et lien uniquement)
-- ---------------------------------------------------------------
create table if not exists articles (
  id            bigint generated by default as identity primary key,
  dedup_key     text not null unique,        -- domaine + titre normalisé
  url           text not null,
  title         text not null,
  excerpt       text,                        -- 280 caractères maximum
  source_id     bigint references sources(id),
  source_name   text not null,
  domain        text,
  lang          text,
  published_at  timestamptz not null,
  fetched_at    timestamptz not null default now()
);
create index if not exists articles_published_idx on articles (published_at desc);

-- ---------------------------------------------------------------
-- Histoires : regroupement des articles qui parlent du même fait
-- ---------------------------------------------------------------
create table if not exists stories (
  id              bigint generated by default as identity primary key,
  personality_id  bigint not null references personalities(id) on delete cascade,
  tokens          text[] not null,           -- mots-clés du premier titre
  headline        text not null,
  first_seen      timestamptz not null,
  last_seen       timestamptz not null,
  article_count   int not null default 1,
  source_count    int not null default 1,
  leaning_count   int not null default 0,    -- nombre de sensibilités différentes qui en parlent
  early_count     int not null default 1,    -- articles parus dans les 12 premières heures
  score           numeric(5,1) not null default 0,
  is_viral        boolean not null default false
);
create index if not exists stories_person_idx on stories (personality_id, last_seen desc);

-- ---------------------------------------------------------------
-- Lien article / personnalité, avec le classement de l'IA
-- ---------------------------------------------------------------
create table if not exists mentions (
  article_id      bigint not null references articles(id) on delete cascade,
  personality_id  bigint not null references personalities(id) on delete cascade,
  story_id        bigint references stories(id) on delete set null,
  stance          text check (stance in ('favorable','defavorable','neutre','hors_sujet')),
  confidence      numeric(3,2),
  satire          boolean,
  argument        text,                      -- étiquette courte : économie, sécurité...
  justification   text,                      -- une phrase, affichée à l'utilisateur
  summary_fr      text,                      -- résumé d'une ligne en français
  model           text,
  prompt_version  text,
  classified_at   timestamptz,
  error           text,
  primary key (article_id, personality_id)
);
create index if not exists mentions_todo_idx on mentions (classified_at) where classified_at is null;
create index if not exists mentions_person_idx on mentions (personality_id, stance);

-- ---------------------------------------------------------------
-- Signalements des utilisateurs
-- ---------------------------------------------------------------
create table if not exists reports (
  id              bigint generated by default as identity primary key,
  article_id      bigint not null references articles(id) on delete cascade,
  personality_id  bigint not null references personalities(id) on delete cascade,
  reason          text not null check (reason in ('mauvais_camp','satire','hors_sujet','illicite','autre')),
  comment         text check (char_length(comment) <= 500),
  status          text not null default 'nouveau' check (status in ('nouveau','valide','rejete')),
  created_at      timestamptz not null default now()
);

-- ---------------------------------------------------------------
-- Vue utilisée par les écrans
-- ---------------------------------------------------------------
create or replace view feed as
select
  m.personality_id,
  m.stance,
  m.confidence,
  m.satire,
  m.argument,
  m.justification,
  m.summary_fr,
  a.id          as article_id,
  a.url,
  a.title,
  a.excerpt,
  a.source_name,
  a.domain,
  a.published_at,
  s.leaning,
  st.id         as story_id,
  st.score      as story_score,
  st.is_viral,
  st.source_count,
  st.leaning_count
from mentions m
join articles a on a.id = m.article_id
left join sources s on s.id = a.source_id
left join stories st on st.id = m.story_id
where m.classified_at is not null;

-- ---------------------------------------------------------------
-- Sécurité : lecture publique, écriture réservée aux tâches serveur
-- (la clé "service role" contourne ces règles)
-- ---------------------------------------------------------------
alter table personalities enable row level security;
alter table sources       enable row level security;
alter table articles      enable row level security;
alter table stories       enable row level security;
alter table mentions      enable row level security;
alter table reports       enable row level security;

drop policy if exists read_personalities on personalities;
create policy read_personalities on personalities for select using (true);
drop policy if exists read_sources on sources;
create policy read_sources on sources for select using (true);
drop policy if exists read_articles on articles;
create policy read_articles on articles for select using (true);
drop policy if exists read_stories on stories;
create policy read_stories on stories for select using (true);
drop policy if exists read_mentions on mentions;
create policy read_mentions on mentions for select using (true);
drop policy if exists insert_reports on reports;
create policy insert_reports on reports for insert with check (status = 'nouveau');

alter view feed set (security_invoker = true);
